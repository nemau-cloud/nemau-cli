// Command gendocs writes the command reference in docs/commands: one Markdown
// page per command, generated from the cobra command tree, and an index.
//
// Run it from the repository root after changing a command, a flag or a help
// text:
//
//	go run ./internal/tools/gendocs
//
// The pages contain no date, version or machine path, so running it twice gives
// the same files. The test next to it fails when the committed pages are stale.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/nemau-cloud/nemau-cli/internal/cli"
	"github.com/spf13/cobra"
)

const header = "<!-- Generated by `go run ./internal/tools/gendocs`. Do not edit by hand. -->\n\n"

func main() {
	dir := flag.String("dir", filepath.Join("docs", "commands"), "directory to write the pages to")
	flag.Parse()
	if err := write(*dir); err != nil {
		fmt.Fprintln(os.Stderr, "gendocs:", err)
		os.Exit(1)
	}
}

// write replaces the Markdown files in dir with freshly generated pages, so a
// removed or renamed command does not leave a stale page behind.
func write(dir string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	old, err := filepath.Glob(filepath.Join(dir, "*.md"))
	if err != nil {
		return err
	}
	for _, path := range old {
		if err := os.Remove(path); err != nil {
			return err
		}
	}
	for name, content := range pages(rootCommand()) {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// rootCommand builds the tree as `nemau` shows it at run time. Cobra adds the
// completion command and the --version flag only when a command executes, so
// they are added here explicitly. Building the tree makes no network call and
// reads no configuration.
func rootCommand() *cobra.Command {
	root := cli.NewRootCommand("dev")
	root.InitDefaultCompletionCmd()
	root.InitDefaultVersionFlag()
	return root
}

// pages returns every page by file name: one per available command, and
// README.md as the index.
func pages(root *cobra.Command) map[string]string {
	out := map[string]string{"README.md": index(root)}
	var visit func(*cobra.Command)
	visit = func(cmd *cobra.Command) {
		out[fileName(cmd)] = page(cmd)
		for _, sub := range children(cmd) {
			visit(sub)
		}
	}
	visit(root)
	return out
}

// children lists the subcommands shown in help, in the order help shows them.
func children(cmd *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	for _, sub := range cmd.Commands() {
		if sub.IsAvailableCommand() && !sub.IsAdditionalHelpTopicCommand() {
			out = append(out, sub)
		}
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].Name() < out[j].Name() })
	return out
}

func fileName(cmd *cobra.Command) string {
	return strings.ReplaceAll(cmd.CommandPath(), " ", "_") + ".md"
}

func page(cmd *cobra.Command) string {
	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "# %s\n\n", cmd.CommandPath())

	if cmd.Long != "" {
		b.WriteString(prose(cmd.Long))
	} else {
		b.WriteString(sentence(cmd.Short) + "\n\n")
	}

	b.WriteString("## Usage\n\n```\n")
	if cmd.Runnable() {
		b.WriteString(cmd.UseLine() + "\n")
	}
	if cmd.HasAvailableSubCommands() {
		b.WriteString(cmd.CommandPath() + " [command]\n")
	}
	b.WriteString("```\n\n")

	if len(cmd.Aliases) > 0 {
		aliases := make([]string, len(cmd.Aliases))
		for i, alias := range cmd.Aliases {
			aliases[i] = "`" + alias + "`"
		}
		label := "Alias"
		if len(aliases) > 1 {
			label = "Aliases"
		}
		fmt.Fprintf(&b, "%s: %s\n\n", label, strings.Join(aliases, ", "))
	}

	if cmd.Example != "" {
		b.WriteString("## Examples\n\n```sh\n" + dedent(cmd.Example) + "\n```\n\n")
	}

	if subs := children(cmd); len(subs) > 0 {
		b.WriteString("## Subcommands\n\n| Command | Description |\n| --- | --- |\n")
		for _, sub := range subs {
			fmt.Fprintf(&b, "| [%s](%s) | %s |\n", sub.Name(), fileName(sub), sub.Short)
		}
		b.WriteString("\n")
	}

	if flags := flagBlock(cmd.LocalFlags().FlagUsages()); flags != "" {
		b.WriteString("## Options\n\n```\n" + flags + "```\n\n")
	}
	if flags := flagBlock(cmd.InheritedFlags().FlagUsages()); flags != "" {
		b.WriteString("## Global options\n\n```\n" + flags + "```\n\n")
	}

	b.WriteString("## See also\n\n")
	if parent := cmd.Parent(); parent != nil {
		fmt.Fprintf(&b, "- [%s](%s): %s\n", parent.CommandPath(), fileName(parent), parent.Short)
	}
	b.WriteString("- [Command reference](README.md)\n")
	return b.String()
}

// index lists every command as a nested list, the root first.
func index(root *cobra.Command) string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("# Command reference\n\n")
	b.WriteString("One page per command, generated from the help texts. Every command also\n")
	b.WriteString("accepts `-h` or `--help`, which prints the same information in the terminal.\n")
	fmt.Fprintf(&b, "The global options are described on the [%s](%s) page.\n\n", root.Name(), fileName(root))
	var visit func(*cobra.Command, int)
	visit = func(cmd *cobra.Command, depth int) {
		fmt.Fprintf(&b, "%s- [%s](%s): %s\n", strings.Repeat("  ", depth), cmd.CommandPath(), fileName(cmd), cmd.Short)
		for _, sub := range children(cmd) {
			visit(sub, depth+1)
		}
	}
	visit(root, 0)
	return b.String()
}

// flagBlock keeps the flag table as help prints it, minus --help, which every
// command has and the index already mentions.
func flagBlock(usages string) string {
	var b strings.Builder
	for _, line := range strings.Split(usages, "\n") {
		line = strings.TrimRight(line, " ")
		if line == "" || strings.HasPrefix(strings.TrimSpace(line), "-h, --help") {
			continue
		}
		b.WriteString(line + "\n")
	}
	return b.String()
}

// placeholder matches the <name> arguments of the help texts, which Markdown
// would otherwise take for HTML tags.
var placeholder = regexp.MustCompile(`<[A-Za-z][A-Za-z0-9._ -]*>`)

// prose turns a help text into Markdown. Unindented lines are paragraphs;
// indented runs, which the help texts use for commands and tables, become code
// blocks.
func prose(text string) string {
	lines := strings.Split(strings.TrimSpace(text), "\n")
	var b strings.Builder
	for i := 0; i < len(lines); {
		line := lines[i]
		if !indented(line) {
			if strings.TrimSpace(line) == "" {
				b.WriteString("\n")
			} else {
				b.WriteString(placeholder.ReplaceAllString(strings.TrimRight(line, " "), "`$0`") + "\n")
			}
			i++
			continue
		}
		// A code block runs over blank lines as long as indented lines follow.
		j := i
		for j < len(lines) && (indented(lines[j]) || (strings.TrimSpace(lines[j]) == "" && j+1 < len(lines) && indented(lines[j+1]))) {
			j++
		}
		if b.Len() > 0 && !strings.HasSuffix(b.String(), "\n\n") {
			b.WriteString("\n")
		}
		b.WriteString("```\n" + dedent(strings.Join(lines[i:j], "\n")) + "\n```\n")
		if j < len(lines) && strings.TrimSpace(lines[j]) != "" {
			b.WriteString("\n")
		}
		i = j
	}
	return strings.TrimRight(b.String(), "\n") + "\n\n"
}

func indented(line string) bool {
	return strings.TrimSpace(line) != "" && (line[0] == ' ' || line[0] == '\t')
}

// dedent removes the leading whitespace the non-blank lines share.
func dedent(text string) string {
	lines := strings.Split(strings.Trim(text, "\n"), "\n")
	common := ""
	first := true
	for _, line := range lines {
		if strings.TrimSpace(line) == "" {
			continue
		}
		lead := line[:len(line)-len(strings.TrimLeft(line, " \t"))]
		if first {
			common, first = lead, false
			continue
		}
		for !strings.HasPrefix(lead, common) {
			common = common[:len(common)-1]
		}
	}
	for i, line := range lines {
		lines[i] = strings.TrimRight(strings.TrimPrefix(line, common), " ")
	}
	return strings.Join(lines, "\n")
}

// sentence ends a short description with a full stop for use as a paragraph.
func sentence(short string) string {
	if short == "" || strings.HasSuffix(short, ".") {
		return short
	}
	return short + "."
}
