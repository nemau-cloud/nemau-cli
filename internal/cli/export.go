package cli

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"time"

	nemau "github.com/nemau-cloud/nemau-sdk-go"
	"github.com/spf13/cobra"
)

// newExportCommand writes the project's infrastructure out as Terraform.
//
// It complements `nemau storage export`, which exports the data. Together they
// let a customer move off the platform, or show an auditor that they can.
//
// It runs entirely on the client and asks the platform to generate nothing, so
// its output can be audited, diffed and re-run without the platform's help.
func newExportCommand() *cobra.Command {
	var outputDir string
	var withImports bool
	cmd := &cobra.Command{
		Use:   "export [directory]",
		Short: "Export the project's infrastructure as Terraform",
		Long: `Export the project's infrastructure as Terraform.

Produces three files:

    nemau.tf        the resources, with dependencies expressed as Terraform
                    references
    imports.tf      "import" blocks (Terraform 1.5+) to adopt what exists
                    instead of recreating it
    inventory.json  the raw inventory exactly as the API returned it

A subnet refers to its network as "nemau_network.app.id", for example. The
configuration therefore replays into an empty project, or can be adapted to
another provider.

This command does not export the contents of object containers (see
"nemau storage export") or instance disks, which the API does not expose.`,
		Args: cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			c, ctx, cancel, err := runCtx(cmd)
			if err != nil {
				return err
			}
			defer cancel()

			destination := outputDir
			if len(args) == 1 {
				destination = args[0]
			}
			if destination == "" {
				destination = "."
			}
			if err := os.MkdirAll(destination, 0o755); err != nil {
				return err
			}

			inventory, warnings := collectInventory(ctx, c)
			for _, warning := range warnings {
				fmt.Fprintln(cmd.ErrOrStderr(), "skipped:", warning)
			}

			document := renderInventory(inventory)
			written := []string{}

			tfPath := filepath.Join(destination, "nemau.tf")
			if err := os.WriteFile(tfPath, []byte(document.render(exportHeader(c))), 0o644); err != nil {
				return err
			}
			written = append(written, tfPath)

			if withImports {
				importPath := filepath.Join(destination, "imports.tf")
				if err := os.WriteFile(importPath, []byte(document.importBlocks()), 0o644); err != nil {
					return err
				}
				written = append(written, importPath)
			}

			raw, err := json.MarshalIndent(inventory, "", "  ")
			if err != nil {
				return err
			}
			jsonPath := filepath.Join(destination, "inventory.json")
			if err := os.WriteFile(jsonPath, append(raw, '\n'), 0o644); err != nil {
				return err
			}
			written = append(written, jsonPath)

			v := view{columns: []string{"FILE", "RESOURCES"}, data: inventory}
			v.rows = append(v.rows, []string{tfPath, itoa(len(document.blocks))})
			for _, path := range written[1:] {
				v.rows = append(v.rows, []string{path, "-"})
			}
			v.ids = written
			return render(cmd, v)
		},
	}
	cmd.Flags().StringVarP(&outputDir, "out", "d", "", "destination directory (default: the current directory)")
	cmd.Flags().BoolVar(&withImports, "imports", true, "also write the Terraform import blocks")
	return cmd
}

func exportHeader(c *nemau.Client) string {
	return fmt.Sprintf(`# Infrastructure exported from Nemau Cloud.
#
#   api       : %s
#   project   : %s
#   exported  : %s
#
# Generated by "nemau export". Ids appear only in imports.tf; dependencies are
# expressed as Terraform references, so this configuration replays into an
# empty project.
#
# This file contains no secrets: no private key, no kubeconfig, no object
# content. SSH keys appear only as their public half.

terraform {
  required_version = ">= 1.5"
  required_providers {
    nemau = {
      source  = "nemau-cloud/nemau"
      version = "~> 0.1"
    }
  }
}

provider "nemau" {
  # Credential read from the environment. Uncomment to pin the project:
  # project = %q
}
`, c.BaseURL(), orDash(c.Project()), time.Now().UTC().Format(time.RFC3339), c.Project())
}

func orDash(value string) string {
	if value == "" {
		return "(the credential's)"
	}
	return value
}

// inventory is everything the export could read. Each slice is independent, so
// one unreadable service (a disabled feature, a missing permission) leaves a gap
// in the export instead of failing it.
type inventory struct {
	Networks       []nemau.Network                 `json:"networks"`
	Subnets        []nemau.Subnet                  `json:"subnets"`
	Interfaces     []nemau.NetworkInterface        `json:"interfaces"`
	SecurityGroups []nemau.SecurityGroup           `json:"security_groups"`
	Keypairs       []nemau.Keypair                 `json:"keypairs"`
	Instances      []nemau.Instance                `json:"instances"`
	Volumes        []nemau.Volume                  `json:"volumes"`
	FloatingIPs    []nemau.FloatingIP              `json:"floating_ips"`
	Containers     []nemau.Container               `json:"containers"`
	DNSZones       []nemau.DNSZone                 `json:"dns_zones"`
	DNSRecordSets  map[string][]nemau.DNSRecordSet `json:"dns_record_sets"`
	LoadBalancers  []nemau.LoadBalancer            `json:"load_balancers"`
	Clusters       []nemau.KubernetesCluster       `json:"kubernetes_clusters"`
}

// collectInventory reads every service, collecting warnings instead of errors.
//
// A project often has services its credential cannot read or its organization
// has not enabled. The export carries on past a 403 so that it still works with
// a narrowly scoped credential.
func collectInventory(ctx context.Context, c *nemau.Client) (inventory, []string) {
	var found inventory
	var warnings []string

	note := func(what string, err error) {
		if err != nil {
			warnings = append(warnings, fmt.Sprintf("%s: %v", what, err))
		}
	}

	var err error
	found.Networks, err = c.Network.ListNetworks(ctx)
	note("networks", err)
	found.Subnets, err = c.Network.ListSubnets(ctx)
	note("subnets", err)
	found.Interfaces, err = c.Network.ListNetworkInterfaces(ctx)
	note("network interfaces", err)
	found.SecurityGroups, err = c.Network.ListSecurityGroups(ctx)
	note("security groups", err)
	found.Keypairs, err = c.Compute.ListKeypairs(ctx)
	note("keypairs", err)
	found.Instances, err = c.Compute.ListInstances(ctx)
	note("instances", err)
	found.Volumes, err = c.Storage.ListVolumes(ctx)
	note("volumes", err)
	found.FloatingIPs, err = c.Network.ListFloatingIPs(ctx)
	note("floating IPs", err)
	found.Containers, err = c.Storage.ListContainers(ctx)
	note("containers", err)
	found.DNSZones, err = c.DNS.ListZones(ctx)
	note("DNS zones", err)
	found.LoadBalancers, err = c.LoadBalancer.List(ctx)
	note("load balancers", err)
	// The listing is only a summary; the topology the HCL needs comes from
	// each cluster's detail.
	clusters, err := c.Kubernetes.ListClusters(ctx)
	note("Kubernetes clusters", err)
	for _, summary := range clusters {
		cluster, err := c.Kubernetes.GetCluster(ctx, summary.Name)
		if err != nil {
			note("Kubernetes cluster "+summary.Name, err)
			continue
		}
		found.Clusters = append(found.Clusters, *cluster)
	}

	found.DNSRecordSets = map[string][]nemau.DNSRecordSet{}
	for _, zone := range found.DNSZones {
		recordSets, err := c.DNS.ListRecordSets(ctx, zone.ID)
		if err != nil {
			note("record sets of "+zone.Name, err)
			continue
		}
		found.DNSRecordSets[zone.ID] = recordSets
	}

	return found, warnings
}
